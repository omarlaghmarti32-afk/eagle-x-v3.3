"""Build public static assets for Fleek/IPFS with a server API origin.

Only the public HTTPS API origin is embedded. Authentication tokens must stay
in the browser session field / server secret store, never in static assets.
"""

from __future__ import annotations

import html
import os
import shutil
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "dist"
MARKER = '<meta name="eagle-api-origin" content="">'


def main() -> None:
    raw_origin = os.environ.get("API_ORIGIN", "").strip()
    parsed = urlsplit(raw_origin)
    if (
        parsed.scheme != "https"
        or not parsed.netloc
        or parsed.username
        or parsed.password
        or parsed.path not in ("", "/")
        or parsed.query
        or parsed.fragment
    ):
        raise SystemExit("Set API_ORIGIN to a public HTTPS origin, e.g. https://api.example.com")

    dashboard_path = ROOT / "dashboard.html"
    dashboard = dashboard_path.read_text(encoding="utf-8")
    if dashboard.count(MARKER) != 1:
        raise SystemExit("dashboard.html must contain exactly one eagle-api-origin meta marker")
    dashboard = dashboard.replace(
        MARKER,
        f'<meta name="eagle-api-origin" content="{html.escape(parsed.scheme + "://" + parsed.netloc, quote=True)}">',
        1,
    )

    OUTPUT.mkdir(parents=True, exist_ok=True)
    (OUTPUT / "dashboard.html").write_text(dashboard, encoding="utf-8")
    shutil.copy2(ROOT / "index.html", OUTPUT / "index.html")
    (OUTPUT / ".eagle-static-build").write_text("generated by scripts/build_static_site.py\n", encoding="utf-8")
    print("Built static dashboard and landing page; no API token was embedded.")


if __name__ == "__main__":
    main()
